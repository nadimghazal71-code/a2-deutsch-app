/**
 * Regenerates mobile/src/vocabData.js from the web app's word lists.
 *
 * The web app loads vocab-a1.js / vocab-a2.js as plain <script> tags that
 * define globals, which Metro cannot consume. Rather than maintain the lists
 * twice by hand, the mobile copy is generated from them, so the two can only
 * ever go out of step by forgetting to run this - which the README says to do.
 *
 *   node tools/build-mobile-vocab.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))

/** Evaluates one of the browser vocab files and returns the array it defines. */
function readList(file, binding) {
  const source = fs.readFileSync(path.join(root, file), 'utf8')
  // eslint-disable-next-line no-new-func
  return new Function(`${source}; return ${binding};`)()
}

const a1 = readList('vocab-a1.js', 'VOCAB_A1')
const a2 = readList('vocab-a2.js', 'VOCAB_A2')

for (const [name, list] of [['A1', a1], ['A2', a2]]) {
  if (!Array.isArray(list) || !list.length) throw new Error(`${name} list is empty`)
  list.forEach((e, i) => {
    if (e.id !== i) throw new Error(`${name} entry ${i} has id ${e.id}; id must equal its index`)
  })
}

const out = `// Generated by tools/build-mobile-vocab.mjs - do not edit by hand.
// Source of truth: ../../vocab-a1.js and ../../vocab-a2.js in the web app.
// Regenerate with: node tools/build-mobile-vocab.mjs

export const VOCAB_A1 = ${JSON.stringify(a1)};

export const VOCAB_A2 = ${JSON.stringify(a2)};
`

const target = path.join(root, 'mobile', 'src', 'vocabData.js')
fs.mkdirSync(path.dirname(target), { recursive: true })
fs.writeFileSync(target, out, 'utf8')

console.log(`wrote ${path.relative(root, target)} — A1: ${a1.length}, A2: ${a2.length}`)
